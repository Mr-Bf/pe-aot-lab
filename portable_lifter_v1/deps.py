"""Build fresh Remill dependencies from pinned offline source archives.

No old static libraries, CMake exports, build directories, or experiment
receipts are inputs. The caller owns command logging and the base environment.
"""
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import shlex
import shutil
import stat
import tarfile
import traceback

PINS = {
    'gflags': ('52e94563eba1968783864942fedf6e87e3c611f4', 'c7e5ee308605b4341a2533340872524b75f07992'),
    'glog': ('7b134a5c82c0c0b5698bb6bf7a835b230c5638e4', '2ea80bbae8012cbe2cfb51acbe121d56319a5d93'),
    'xed': ('dc6bdbe036515c7ef55d3b2d50bafc5232bfe534', 'aeee3e5be980a4feaca6427bfaf9c64cdde245c8'),
    'mbuild': ('7c4497f41f576b43a80bb0f8d8452bbcfd58b6e2', '5240cf4ea48b49ab4983eb5f93890b8e92ff9dac'),
}
LICENSES = {'gflags': 'COPYING.txt', 'glog': 'COPYING', 'xed': 'LICENSE', 'mbuild': 'LICENSE'}
LOCK = Path(__file__).with_name('cache-lock.json')

XED_CONFIG = '''# Generated by portable_lifter_v1.deps; paths follow this installation.
include_guard(GLOBAL)
get_filename_component(_XED_PREFIX "${CMAKE_CURRENT_LIST_DIR}/../../.." ABSOLUTE)
foreach(_XED_PART XED ILD)
  if(_XED_PART STREQUAL "XED")
    set(_XED_ARCHIVE "${_XED_PREFIX}/lib/libxed.a")
  else()
    set(_XED_ARCHIVE "${_XED_PREFIX}/lib/libxed-ild.a")
  endif()
  if(NOT EXISTS "${_XED_ARCHIVE}")
    message(FATAL_ERROR "Missing XED archive: ${_XED_ARCHIVE}")
  endif()
  if(NOT TARGET XED::${_XED_PART})
    add_library(XED::${_XED_PART} STATIC IMPORTED)
    set_target_properties(XED::${_XED_PART} PROPERTIES
      IMPORTED_LOCATION "${_XED_ARCHIVE}"
      INTERFACE_INCLUDE_DIRECTORIES "${_XED_PREFIX}/include")
  endif()
endforeach()
set(XED_FOUND ON)
unset(_XED_PREFIX)
unset(_XED_PART)
unset(_XED_ARCHIVE)
'''


def require(ok, message):
    if not ok:
        raise ValueError(message)


def sha(path):
    value = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            value.update(chunk)
    return value.hexdigest()


def write(path, value):
    with Path(path).open('x') as stream:
        json.dump(value, stream, sort_keys=True, indent=2); stream.write('\n')


def tree(directory):
    result = {}
    for path in sorted(Path(directory).rglob('*')):
        require(not path.is_symlink(), 'source/install symlink not supported: ' + str(path))
        if path.is_file():
            require(path.stat().st_nlink == 1, 'source/install hardlink not supported: ' + str(path))
            result[str(path.relative_to(directory))] = dict(sha256=sha(path), mode=stat.S_IMODE(path.stat().st_mode))
        else:
            require(path.is_dir(), 'non-regular tree member: ' + str(path))
    return result


def static_library(path):
    require(path.is_file() and not path.is_symlink(), 'fresh static library absent: ' + path.name)
    with path.open('rb') as stream:
        require(stream.read(8) == b'!<arch>\n', 'not a static ar archive: ' + path.name)
    return dict(path=str(path), sha256=sha(path))


def merge_xed(stage, prefix):
    """Merge selected XED files without giving its resetting installer our prefix."""
    require(stage == stage.resolve() and stage.is_dir(), 'real XED installation stage absent')
    require(prefix == prefix.resolve() and prefix.is_dir(), 'real dependency install prefix required')
    staged = tree(stage)
    headers = stage / 'include/xed'
    require(headers.is_dir() and not headers.is_symlink(), 'XED staged header directory absent')
    for name in ('xed-interface.h', 'xed-ild.h'):
        require((headers / name).is_file(), 'XED staged header absent: ' + name)
    for name in ('libxed.a', 'libxed-ild.a'):
        static_library(stage / 'lib' / name)
    selected = sorted(name for name in staged if name.startswith('include/xed/') or
                      name in ('lib/libxed.a', 'lib/libxed-ild.a'))
    before = tree(prefix)
    for name in selected:
        target = prefix / name
        require(not target.exists() and not target.is_symlink(), 'XED merge destination already exists: ' + name)
    merged = {}
    for name in selected:
        original = stage / name; target = prefix / name
        target.parent.mkdir(parents=True, exist_ok=True)
        with original.open('rb') as source, target.open('xb') as output:
            shutil.copyfileobj(source, output)
        target.chmod(staged[name]['mode'])
        merged[name] = dict(sha256=sha(target), mode=stat.S_IMODE(target.stat().st_mode))
        require(merged[name] == staged[name], 'XED merged file differs: ' + name)
    require(tree(prefix) == {**before, **merged}, 'XED merge changed previous dependency files')
    require(tree(stage) == staged, 'XED installation stage changed during merge')
    return dict(prefix=str(stage), installed_files=staged, merged_files=merged,
                preserved_install_files=before)


def sources(cache):
    cache = Path(cache).absolute()
    require(cache == cache.resolve() and cache.is_dir(), 'real offline cache directory required')
    metadata = cache / 'cache.json'
    require(metadata.is_file() and not metadata.is_symlink(), 'cache.json must be a regular local file')
    record = json.loads(metadata.read_bytes())
    require(type(record) is dict and record.get('schema') == 1 and type(record.get('sources')) is dict,
            'cache schema 1 with sources required')
    lock = json.loads(LOCK.read_bytes())
    require(type(lock) is dict and lock.get('schema') == 1 and type(lock.get('sources')) is dict,
            'versioned cache lock missing or invalid')
    selected = {}
    for name, (commit, expected_tree) in PINS.items():
        entry = record['sources'].get(name)
        require(type(entry) is dict and entry.get('archive') == name + '.tar' and
                entry.get('commit') == commit and entry.get('tree') == expected_tree,
                'fixed source identity differs: ' + name)
        require({key: entry.get(key) for key in ('archive', 'sha256', 'commit', 'tree')} == lock['sources'].get(name),
                'source differs from versioned cache lock: ' + name)
        digest = entry.get('sha256')
        require(type(digest) is str and re.fullmatch('[0-9a-f]{64}', digest), 'invalid archive digest: ' + name)
        archive = cache / entry['archive']
        require(archive.is_file() and not archive.is_symlink() and sha(archive) == digest,
                'archive missing or digest differs: ' + name)
        selected[name] = dict(archive=str(archive), sha256=digest, commit=commit, tree=expected_tree)
    return dict(cache=str(cache), metadata_sha256=sha(metadata), lock_sha256=sha(LOCK), archives=selected)


def extract(archive, destination, name):
    require(not destination.exists(), 'source destination already exists')
    with tarfile.open(archive, 'r:') as stream:
        members = stream.getmembers()
        require(bool(members), 'empty source archive')
        seen = set()
        for member in members:
            path = PurePosixPath(member.name)
            require(not path.is_absolute() and path.parts and path.parts[0] == name and
                    '..' not in path.parts and str(path) not in seen and
                    (member.isdir() or member.isfile()), 'unsafe/duplicate/link archive member: ' + member.name)
            seen.add(str(path))
        stream.extractall(destination.parent, members=members, filter='data')
    require(destination.is_dir() and not destination.is_symlink(), 'expected source root absent')
    return tree(destination)


def plans(prefix, source, builds, tools, sdk, python, jobs):
    cmake = Path(tools['paths']['cmake']); ninja = Path(tools['paths']['ninja'])
    llvm = Path(tools['paths']['llvm'])
    common = ['-G', 'Ninja', '-DCMAKE_BUILD_TYPE=Release', '-DBUILD_SHARED_LIBS=OFF',
              '-DCMAKE_POSITION_INDEPENDENT_CODE=ON', '-DCMAKE_OSX_ARCHITECTURES=arm64',
              '-DCMAKE_OSX_SYSROOT=' + str(sdk), '-DCMAKE_C_COMPILER=/usr/bin/clang',
              '-DCMAKE_CXX_COMPILER=/usr/bin/clang++', '-DCMAKE_MAKE_PROGRAM=' + str(ninja),
              '-DCMAKE_INSTALL_PREFIX=' + str(prefix), '-DCMAKE_INSTALL_LIBDIR=lib',
              '-DCMAKE_PREFIX_PATH=' + str(prefix), '-DCMAKE_POLICY_VERSION_MINIMUM=3.21',
              '-DCMAKE_FIND_USE_PACKAGE_REGISTRY=OFF', '-DCMAKE_FIND_USE_SYSTEM_PACKAGE_REGISTRY=OFF',
              '-DCMAKE_FIND_USE_CMAKE_ENVIRONMENT_PATH=OFF', '-DCMAKE_EXPORT_NO_PACKAGE_REGISTRY=ON',
              '-DBUILD_TESTING=OFF']
    result = []
    options = {
        'gflags': ['-DBUILD_STATIC_LIBS=ON', '-DBUILD_gflags_LIB=ON', '-DBUILD_gflags_nothreads_LIB=ON',
                   '-DREGISTER_BUILD_DIR=OFF', '-DREGISTER_INSTALL_PREFIX=OFF', '-DGFLAGS_BUILD_TESTING=OFF'],
        'glog': ['-DWITH_GFLAGS=ON', '-DGFLAGS_USE_TARGET_NAMESPACE=ON', '-DWITH_GTEST=OFF', '-DWITH_GMOCK=OFF',
                 '-DCMAKE_DISABLE_FIND_PACKAGE_GTest=ON',
                 '-DWITH_UNWIND=libunwind', '-Dgflags_DIR=' + str(prefix / 'lib/cmake/gflags'),
                 '-DUnwind_INCLUDE_DIR=' + str(llvm / 'include'),
                 '-DUnwind_LIBRARY=' + str(llvm / 'lib/libunwind.dylib')],
    }
    for name in ('gflags', 'glog'):
        build = builds / name
        result.extend([
            (name + '-configure', [cmake, '-S', source / name, '-B', build, *common, *options[name]], None, None),
            (name + '-build', [cmake, '--build', build, '--parallel', str(jobs)], None, None),
            (name + '-install', [cmake, '--install', build], None, None),
        ])
    flags = shlex.join(['-arch', 'arm64', '-isysroot', str(sdk)])
    result.append(('xed-build-install', [python, '-S', source / 'xed/mfile.py', 'install',
        '--install-dir=' + str(builds / 'xed-install'), '--build-dir=' + str(builds / 'xed'),
        '--cc=/usr/bin/clang', '--cxx=/usr/bin/clang++', '--compiler=clang', '--host-cpu=aarch64',
        '--extra-flags=' + flags, '--extra-linkflags=' + flags, '-j', str(jobs)],
        source / 'xed', {'SDKROOT': str(sdk), 'PYTHONDONTWRITEBYTECODE': '1',
                         'PYTHONNOUSERSITE': '1', 'PYTHONPATH': str(source / 'mbuild')}))
    return result


def build(prefix, cache, tools, sdk, python, run, jobs=2):
    require(type(jobs) is int and 1 <= jobs <= 8, 'jobs must be integer 1..8')
    prefix = Path(prefix).absolute(); sdk = Path(sdk).absolute(); python = Path(python).absolute()
    require(prefix == prefix.resolve() and not prefix.exists(), 'fresh real install prefix required')
    source = prefix.with_name(prefix.name + '-sources'); builds = prefix.with_name(prefix.name + '-build')
    require(not source.exists() and not builds.exists(), 'preserve existing dependency source/build directories')
    require(sdk.is_dir() and python.is_file(), 'explicit SDK and Python must exist')
    inventory = sources(cache)
    for name in ('cmake', 'ninja'):
        require(Path(tools['paths'][name]).is_file(), 'required new tool absent: ' + name)
    llvm = Path(tools['paths']['llvm'])
    require((llvm / 'include/unwind.h').is_file() and (llvm / 'lib/libunwind.dylib').is_file(),
            'new LLVM unwind headers/library required; no global fallback')
    prefix.mkdir(parents=True); source.mkdir(); builds.mkdir()
    record = dict(schema=1, status='STARTED_NOT_BUILT', prefix=str(prefix), source_root=str(source),
                  build_root=str(builds), source_inputs=inventory, commands=[], jobs=jobs,
                  sdk=str(sdk), python=str(python), libraries={}, guest_executions=0)
    write(builds / 'started.json', record)
    try:
        source_trees = {}
        for name, entry in inventory['archives'].items():
            source_trees[name] = extract(entry['archive'], source / name, name)
            require((source / name / LICENSES[name]).is_file(), 'source license absent: ' + name)
        for label, argv, cwd, env in plans(prefix, source, builds, tools, sdk, python, jobs):
            if label == 'xed-build-install':
                stage = builds / 'xed-install'
                require(not stage.exists() and not stage.is_symlink(), 'preserve existing XED installation stage')
                before_xed = tree(prefix)
                for name in ('libgflags.a', 'libgflags_nothreads.a', 'libglog.a'):
                    static_library(prefix / 'lib' / name)
                record['xed_install'] = dict(prefix=str(stage), status='NOT_MERGED')
            command = run(list(map(str, argv)), label, cwd=str(cwd) if cwd else None, env=env)
            require(type(command) is dict and command.get('returncode') == 0, 'dependency command did not succeed: ' + label)
            record['commands'].append(command)
            if label == 'xed-build-install':
                require(tree(prefix) == before_xed, 'XED installer changed shared dependency prefix')
                record['xed_install'] = merge_xed(stage, prefix)
        required_libraries = ('libgflags.a', 'libgflags_nothreads.a', 'libglog.a', 'libxed.a', 'libxed-ild.a')
        for name in required_libraries:
            record['libraries'][name] = static_library(prefix / 'lib' / name)
        for name in ('gflags/gflags.h', 'glog/logging.h', 'xed/xed-interface.h', 'xed/xed-ild.h'):
            require((prefix / 'include' / name).is_file(), 'installed dependency header absent: ' + name)
        xed = prefix / 'lib/cmake/XED'; xed.mkdir(parents=True, exist_ok=False)
        (xed / 'XEDConfig.cmake').write_text(XED_CONFIG)
        require(not (prefix / 'lib/cmake/llvm').exists(), 'unexpected LLVM forwarding package')
        licenses = prefix / 'share/portable-lifter/licenses'; licenses.mkdir(parents=True)
        record['licenses'] = {}
        for name, relative in LICENSES.items():
            target = licenses / (name + '-' + relative)
            shutil.copy2(source / name / relative, target)
            record['licenses'][name] = dict(path=str(target), sha256=sha(target))
        require(source_trees == {name: tree(source / name) for name in PINS}, 'dependency source tree changed during build')
        require(inventory == sources(cache), 'offline input archives changed during build')
        record.update(status='BUILT_FROM_FIXED_OFFLINE_SOURCES_NOT_LIFTER_VERIFIED',
                      source_trees=source_trees, installed_files=tree(prefix),
                      scope='fresh static gflags/glog/XED dependencies; no previous binaries/exports/receipts; native object architecture and lifter integration require caller validation')
        write(builds / 'result.json', record)
        return record
    except Exception as error:
        write(builds / 'failure.json', dict(status='BUILD_FAILED', error_type=type(error).__name__, error=str(error),
                                          commands=record['commands'], xed_install=record.get('xed_install')))
        (builds / 'failure.txt').write_text(traceback.format_exc())
        raise
